/**
 * Returns instant deterministic answer for app navigation / how-to questions
 * @param {string} userMessage
 * @returns {string|null}
 */
export function getExactAppHelpAnswer(userMessage) {
  const text = String(userMessage || '').toLowerCase();

  // 1. Изменение калорий и целей
  if (text.includes('калори') && (text.includes('изменить') || text.includes('поменять') || text.includes('цель') || text.includes('настроить') || text.includes('где'))) {
    return 'Чтобы изменить цель по калориям и белку:\n\n1. Открой вкладку **Food (Питание)**.\n2. В блоке сверху нажми на кнопку **«Цель 2250 ›»** (рядом с оставшимися калориями).\n3. В открывшемся окне укажи новую дневную норму калорий и белка в граммах.\n4. Нажми **«Сохранить цели»**. Новые значения сразу отобразятся на экранах Food и Today.';
  }

  // 2. Удаление и управление ритуалами
  if ((text.includes('ритуал') || text.includes('привычк') || text.includes('фактор')) && (text.includes('удалить') || text.includes('убрать') || text.includes('как') || text.includes('управлять'))) {
    return 'Чтобы удалить ритуал или фактор из дневника:\n\n1. Открой вкладку **Rituals (Ритуалы)**.\n2. В строке **«СЕГОДНЯШНИЕ ФАКТОРЫ»** нажми кнопку **«Управлять»** (она переключится в режим **«Готово»**).\n3. На правом краю строки пользовательского фактора появится **иконка корзины**.\n4. Нажми на корзину и подтверди удаление в модальном окне.\n\n*Фактор исчезнет из списка будущих отметок, а все исторические записи за прошлые дни сохранятся.*';
  }

  // 3. Запуск спортивного таймера
  if (text.includes('emom') || text.includes('табата') || (text.includes('таймер') && (text.includes('как') || text.includes('где') || text.includes('запустить')))) {
    return 'Чтобы запустить спортивный таймер (EMOM, Табата, Интервалы):\n\n1. Открой вкладку **Train (Тренировка)**.\n2. Переключись на подвкладку **«Таймер»** сверху.\n3. Выбери нужный режим:\n   • **Секундомер** — классический хронометраж сета;\n   • **Интервалы** — настройка раундов работы и отдыха;\n   • **EMOM** — выполнение задания каждую минуту;\n   • **Табата** — пресет 8 раундов по 20с работы / 10с отдыха.\n4. Нажми **«СТАРТ»** (таймер запустит обратный отсчет 3-2-1 со звуковыми сигналами).';
  }

  // 4. Применить / использовать шаблон тренировки
  if (text.includes('шаблон') && (text.includes('применить') || text.includes('использовать') || text.includes('выбрать') || text.includes('запустить') || text.includes('начать'))) {
    return 'Чтобы применить и начать тренировку по шаблону:\n\n1. Открой вкладку **Train (Тренировка)**.\n2. Перейди в подвкладку **«Шаблоны»** в верхней панели.\n3. Нажми на любой сохранённый шаблон в списке **«МОИ ШАБЛОНЫ»**.\n4. Приложение сразу загрузит упражнения шаблона и запустит активную тренировку.';
  }

  // 5. Создать новый шаблон тренировки
  if ((text.includes('шаблон') || text.includes('тренировк')) && (text.includes('создать') || text.includes('новый') || text.includes('как') || text.includes('добавить') || text.includes('сохранить'))) {
    return 'Чтобы создать новый шаблон тренировки:\n\n1. Открой вкладку **Train (Тренировка)**.\n2. Перейди в подвкладку **«Шаблоны»**.\n3. Нажми кнопку **«+ Новый шаблон»** прямо под заголовком «МОИ ШАБЛОНЫ».\n4. Укажи название (например, «Push A» или «Спина + Бицепс»), добавь упражнения и нажми **«Сохранить»**.\n\n*Шаблон сохранится в базе и будет доступен для мгновенного запуска.*';
  }

  // 6. Где шаблоны
  if (text.includes('шаблон') && (text.includes('где') || text.includes('найти') || text.includes('посмотреть') || text.includes('список'))) {
    return 'Твои шаблоны тренировок находятся:\n\n1. Вкладка **Train (Тренировка)** в нижнем меню.\n2. Подвкладка **«Шаблоны»** в верхней панели переключения (Силовая / Таймер / Шаблоны / История).\n3. В списке «МОИ ШАБЛОНЫ» отображаются все созданные сплиты с быстрым запуском в один клик.';
  }

  // 7. Источники данных
  if (text.includes('источник') || text.includes('whoop') || text.includes('устройств') || text.includes('apple health')) {
    return 'Управление источниками данных:\n\n1. Нажми на **иконку чипа** в правом верхнем углу экранов **Today** или **AI Intelligence** (или через меню настроек).\n2. В окне **«Источники данных»** отображаются:\n   • **Whoop 4.0** (статус подключения и синхронизации);\n   • **Apple Health** (подключение через HealthKit);\n   • **Garmin Connect** и **Samsung Health** (в разработке);\n   • Стратегия приоритета носимых устройств для HRV и исключения дублирования тренировок.';
  }

  return null;
}
